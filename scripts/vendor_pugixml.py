#!/usr/bin/env python3
"""Vendor a pugixml release into src/private/mxpugi under the mxpugi namespace.

mx compiles its own copy of pugixml. Upstream puts everything in the `pugi`
namespace, so a consumer that also links pugixml would get duplicate symbols
from mx. To avoid that, mx keeps its copy under a private namespace, `mxpugi`,
and under file names that cannot collide with a stock pugixml on the same
include path. This script does that rename mechanically so a refresh to a
newer pugixml is a one-line command instead of a hand edit:

    python3 scripts/vendor_pugixml.py --version 1.16 [--out src/private/mxpugi]

It downloads the release tarball into a fresh temporary directory, extracts it
there (never into the repository), rewrites the three source files and the
license, and writes the result to the output directory, replacing whatever was
there. The rewrite is a set of word-boundary-aware substitutions; the
PUGIXML_* configuration macros are left alone because they are not link
symbols. Running the script twice for the same version produces no diff.

Standard library only; safe to run as `python3 -I`.
"""

import argparse
import io
import os
import re
import shutil
import sys
import tarfile
import tempfile
import urllib.request

RELEASE_URL = "https://github.com/zeux/pugixml/releases/download/v{version}/pugixml-{version}.tar.gz"

# Upstream file name -> vendored file name. The vendored names are distinct
# from upstream's so a stock pugixml.hpp and mxpugi.hpp can share one include
# path without shadowing each other.
SOURCE_FILES = {
    "src/pugixml.hpp": "mxpugi.hpp",
    "src/pugixml.cpp": "mxpugi.cpp",
    "src/pugiconfig.hpp": "mxpugiconfig.hpp",
}

# Upstream ships the license at the tarball root; the name has varied.
LICENSE_CANDIDATES = ("LICENSE.md", "LICENSE", "LICENSE.txt")
LICENSE_OUT = "pugilicense.txt"

# Each entry is (pattern, replacement). Order matters only for readability;
# the patterns do not overlap.
REWRITES = [
    # `namespace pugi` covers the namespace openings, the PUGI_IMPL_NS_BEGIN
    # macro, and any `using namespace pugi`.
    (re.compile(r"\bnamespace(\s+)pugi\b"), r"namespace\1mxpugi"),
    # Qualified names. The lookbehind keeps an already-prefixed `mxpugi::`
    # (or any other identifier ending in pugi) untouched.
    (re.compile(r"(?<![A-Za-z0-9_])pugi::"), "mxpugi::"),
    # Includes between the vendored files.
    (re.compile(r'#(\s*)include(\s+)"pugiconfig\.hpp"'), r'#\1include\2"mxpugiconfig.hpp"'),
    (re.compile(r'#(\s*)include(\s+)"pugixml\.hpp"'), r'#\1include\2"mxpugi.hpp"'),
    # The header-only mode (PUGIXML_HEADER_ONLY) includes the source file by
    # name from the bottom of the header.
    (re.compile(r'"pugixml\.cpp"'), '"mxpugi.cpp"'),
    # Include guards. Renamed so including both the stock header and this one
    # in a single translation unit does not skip either body.
    (re.compile(r"\bHEADER_PUGIXML_HPP\b"), "HEADER_MXPUGI_HPP"),
    (re.compile(r"\bHEADER_PUGICONFIG_HPP\b"), "HEADER_MXPUGICONFIG_HPP"),
    (re.compile(r"\bSOURCE_PUGIXML_CPP\b"), "SOURCE_MXPUGI_CPP"),
]

# Anything matching these after the rewrite means the rename is incomplete,
# and a global pugi:: symbol would leak out of the build.
LEFTOVERS = [
    ("namespace pugi", re.compile(r"\bnamespace\s+pugi\b")),
    ("pugi::", re.compile(r"(?<![A-Za-z0-9_])pugi::")),
    ('#include "pugixml.hpp"', re.compile(r'#\s*include\s+"pugixml\.hpp"')),
    ('#include "pugiconfig.hpp"', re.compile(r'#\s*include\s+"pugiconfig\.hpp"')),
    ('"pugixml.cpp"', re.compile(r'"pugixml\.cpp"')),
    ("HEADER_PUGIXML_HPP", re.compile(r"\bHEADER_PUGIXML_HPP\b")),
    ("HEADER_PUGICONFIG_HPP", re.compile(r"\bHEADER_PUGICONFIG_HPP\b")),
    ("SOURCE_PUGIXML_CPP", re.compile(r"\bSOURCE_PUGIXML_CPP\b")),
]

README_TEMPLATE = """# mxpugi

pugixml {version}, vendored from <https://github.com/zeux/pugixml> and renamed into the
`mxpugi` namespace so that mx does not define any global `pugi::` symbol and can be linked
to a consumer's own pugixml. The file names differ from upstream's for the same reason:
`mxpugi.hpp` and a stock `pugixml.hpp` can share one include path.

Generated by `scripts/vendor_pugixml.py`. Do not hand-edit. Refresh with:

    make vendor-pugixml VERSION=x.y

Only link symbols are renamed. The `PUGIXML_*` configuration macros are the same as upstream's,
so a consumer-wide definition such as `PUGIXML_WCHAR_MODE` also changes how this copy compiles.

Upstream is MIT licensed; see `pugilicense.txt`.
"""


def fail(message):
    print(f"vendor_pugixml: {message}", file=sys.stderr)
    sys.exit(1)


def download(url, dest):
    print(f"downloading {url}")
    try:
        with urllib.request.urlopen(url) as response, open(dest, "wb") as out:
            shutil.copyfileobj(response, out)
    except Exception as error:  # pylint: disable=broad-except
        fail(f"download failed: {error}")


def extract(tarball, into):
    with tarfile.open(tarball, "r:gz") as tar:
        # The 'data' filter refuses absolute paths, links outside the tree, and
        # other tricks a hostile archive could play. It exists from Python 3.12.
        if hasattr(tarfile, "data_filter"):
            tar.extractall(into, filter="data")
        else:
            tar.extractall(into)


def find_root(extracted, version):
    expected = os.path.join(extracted, f"pugixml-{version}")
    if os.path.isdir(expected):
        return expected
    entries = [e for e in os.listdir(extracted) if os.path.isdir(os.path.join(extracted, e))]
    if len(entries) == 1:
        return os.path.join(extracted, entries[0])
    fail(f"could not find the extracted pugixml-{version} directory under {extracted}")
    return None


def read_text(path):
    with io.open(path, "r", encoding="utf-8", newline="") as handle:
        return handle.read()


def write_text(path, text):
    with io.open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(text)


def rewrite(text, name):
    for pattern, replacement in REWRITES:
        text = pattern.sub(replacement, text)
    problems = []
    for label, pattern in LEFTOVERS:
        for match in pattern.finditer(text):
            line = text.count("\n", 0, match.start()) + 1
            problems.append(f"{name}:{line}: {label} survived the rewrite")
    if problems:
        fail("\n".join(problems))
    return text


def find_license(root):
    for candidate in LICENSE_CANDIDATES:
        path = os.path.join(root, candidate)
        if os.path.isfile(path):
            return path
    fail(f"no license file found at the tarball root (tried {', '.join(LICENSE_CANDIDATES)})")
    return None


def vendor(version, out_dir):
    with tempfile.TemporaryDirectory(prefix="vendor-pugixml-") as temp:
        tarball = os.path.join(temp, "pugixml.tar.gz")
        download(RELEASE_URL.format(version=version), tarball)
        extracted = os.path.join(temp, "extracted")
        os.mkdir(extracted)
        extract(tarball, extracted)
        root = find_root(extracted, version)

        outputs = {}
        for upstream_name, vendored_name in SOURCE_FILES.items():
            source = os.path.join(root, upstream_name)
            if not os.path.isfile(source):
                fail(f"{upstream_name} is missing from the release tarball")
            outputs[vendored_name] = rewrite(read_text(source), vendored_name)
        outputs[LICENSE_OUT] = read_text(find_license(root))
        outputs["README.md"] = README_TEMPLATE.format(version=version)

    # Everything is in memory before the output directory is touched, so a
    # failure above leaves the previous vendored copy intact.
    if os.path.isdir(out_dir):
        shutil.rmtree(out_dir)
    os.makedirs(out_dir)
    for name, text in outputs.items():
        write_text(os.path.join(out_dir, name), text)
        print(f"wrote {os.path.join(out_dir, name)}")


def main():
    parser = argparse.ArgumentParser(description="Vendor pugixml under the mxpugi namespace.")
    parser.add_argument("--version", required=True, help="pugixml release to vendor, e.g. 1.16")
    parser.add_argument("--out", default="src/private/mxpugi", help="output directory (default: src/private/mxpugi)")
    args = parser.parse_args()
    if not re.fullmatch(r"\d+\.\d+(\.\d+)?", args.version):
        fail(f"--version must look like 1.16, got {args.version!r}")
    vendor(args.version, args.out)


if __name__ == "__main__":
    main()
